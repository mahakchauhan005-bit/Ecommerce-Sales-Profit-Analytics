-- ========================================================

CREATE OR ALTER VIEW dbo.vw_PaymentPerformance
AS

SELECT
    payment_type AS PaymentType,

    COUNT(DISTINCT order_id) AS TotalOrders,

    SUM(payment_value) AS TotalPaymentValue,

    CAST(
        AVG(payment_value)
        AS DECIMAL(12,2)
    ) AS AveragePaymentValue,

    SUM(payment_installments) AS TotalInstallments

FROM dbo.olist_order_payments_dataset

GROUP BY
    payment_type;
GO


