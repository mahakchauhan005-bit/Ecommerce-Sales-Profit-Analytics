WITH CustomerMetrics AS
(
    SELECT
        c.customer_unique_id AS CustomerUniqueID,

        -- Most recent purchase date for the customer
        MAX(
            TRY_CONVERT(
                DATETIME2,
                o.order_purchase_timestamp
            )
        ) AS LastPurchaseDate,

        -- Number of distinct orders
        COUNT(DISTINCT o.order_id) AS Frequency,

        -- Total revenue generated by the customer
        SUM(oi.price) AS MonetaryValue

    FROM dbo.olist_customers_dataset AS c

    INNER JOIN dbo.olist_orders_dataset AS o
        ON c.customer_id = o.customer_id

    INNER JOIN dbo.olist_order_items_dataset AS oi
        ON o.order_id = oi.order_id

    WHERE o.order_purchase_timestamp IS NOT NULL

    GROUP BY
        c.customer_unique_id
),

DatasetEnd AS
(
    SELECT
        MAX(
            TRY_CONVERT(
                DATETIME2,
                order_purchase_timestamp
            )
        ) AS DatasetMaxPurchaseDate

    FROM dbo.olist_orders_dataset

    WHERE order_purchase_timestamp IS NOT NULL
)

SELECT
    cm.CustomerUniqueID,

    cm.LastPurchaseDate,

    -- Recency: days since the customer's last purchase
    DATEDIFF(
        DAY,
        cm.LastPurchaseDate,
        de.DatasetMaxPurchaseDate
    ) AS RecencyDays,

    -- Frequency: number of distinct orders
    cm.Frequency,

    -- Monetary: total customer revenue
    cm.MonetaryValue

FROM CustomerMetrics AS cm

CROSS JOIN DatasetEnd AS de

ORDER BY
    cm.MonetaryValue DESC;
GO

