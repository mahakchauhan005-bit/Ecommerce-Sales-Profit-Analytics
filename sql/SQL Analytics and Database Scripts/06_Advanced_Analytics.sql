-- Q2: RFM Customer Scoring
-- =========================================================

WITH CustomerRFM AS
(
    SELECT
        c.customer_unique_id AS CustomerUniqueID,

        MAX(
            TRY_CONVERT(
                DATETIME2,
                o.order_purchase_timestamp
            )
        ) AS LastPurchaseDate,

        COUNT(DISTINCT o.order_id) AS Frequency,

        SUM(oi.price) AS MonetaryValue

    FROM dbo.olist_customers_dataset AS c

    INNER JOIN dbo.olist_orders_dataset AS o
        ON c.customer_id = o.customer_id

    INNER JOIN dbo.olist_order_items_dataset AS oi
        ON o.order_id = oi.order_id

    GROUP BY
        c.customer_unique_id
),

DatasetEnd AS
(
    SELECT
        MAX(
            TRY_CONVERT(
                DATETIME2,
                order_purchase_timestamp
            )
        ) AS DatasetMaxDate

    FROM dbo.olist_orders_dataset
),

RFMBase AS
(
    SELECT
        r.CustomerUniqueID,

        DATEDIFF(
            DAY,
            r.LastPurchaseDate,
            d.DatasetMaxDate
        ) AS RecencyDays,

        r.Frequency,

        r.MonetaryValue

    FROM CustomerRFM AS r
    CROSS JOIN DatasetEnd AS d
)

SELECT
    CustomerUniqueID,
    RecencyDays,
    Frequency,
    MonetaryValue,

    -- Lower recency = better score
    CASE
        WHEN RecencyDays <= 30 THEN 5
        WHEN RecencyDays <= 90 THEN 4
        WHEN RecencyDays <= 180 THEN 3
        WHEN RecencyDays <= 365 THEN 2
        ELSE 1
    END AS RecencyScore,

    CASE
        WHEN Frequency >= 5 THEN 5
        WHEN Frequency = 4 THEN 4
        WHEN Frequency = 3 THEN 3
        WHEN Frequency = 2 THEN 2
        ELSE 1
    END AS FrequencyScore,

    CASE
        WHEN MonetaryValue >= 1000 THEN 5
        WHEN MonetaryValue >= 500 THEN 4
        WHEN MonetaryValue >= 250 THEN 3
        WHEN MonetaryValue >= 100 THEN 2
        ELSE 1
    END AS MonetaryScore

FROM RFMBase
ORDER BY
    MonetaryValue DESC;
GO

