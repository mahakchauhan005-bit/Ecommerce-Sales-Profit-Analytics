-- Q6: Product Category Review Performance View
-- =========================================================

CREATE OR ALTER VIEW dbo.vw_CategoryReviewPerformance
AS

SELECT
    COALESCE(
        t.product_category_name_english,
        p.product_category_name,
        'Unknown'
    ) AS ProductCategory,

    COUNT(DISTINCT r.review_id) AS TotalReviews,

    CAST(
        AVG(
            CAST(r.review_score AS DECIMAL(10,2))
        )
        AS DECIMAL(10,2)
    ) AS AverageReviewScore,

    SUM(
        CASE
            WHEN r.review_score IN (4,5)
            THEN 1
            ELSE 0
        END
    ) AS PositiveReviews,

    SUM(
        CASE
            WHEN r.review_score = 3
            THEN 1
            ELSE 0
        END
    ) AS NeutralReviews,

    SUM(
        CASE
            WHEN r.review_score IN (1,2)
            THEN 1
            ELSE 0
        END
    ) AS NegativeReviews

FROM dbo.olist_products_dataset AS p

INNER JOIN dbo.olist_order_items_dataset AS oi
    ON p.product_id = oi.product_id

INNER JOIN dbo.olist_order_reviews_dataset AS r
    ON oi.order_id = r.order_id

LEFT JOIN dbo.product_category_name_translation AS t
    ON p.product_category_name = t.product_category_name

GROUP BY
    COALESCE(
        t.product_category_name_english,
        p.product_category_name,
        'Unknown'
    );
GO


-- Test the view

SELECT TOP 10 *
FROM dbo.vw_CategoryReviewPerformance
ORDER BY AverageReviewScore DESC;
GO

