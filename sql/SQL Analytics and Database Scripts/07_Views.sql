-- Q3: Product Performance View
-- =========================================================

USE EcommerceAnalytics;
GO

CREATE OR ALTER VIEW dbo.vw_ProductPerformance
AS

SELECT
    p.product_id AS ProductID,

    COALESCE(
        t.product_category_name_english,
        p.product_category_name,
        'Unknown'
    ) AS ProductCategory,

    -- Number of items sold
    COUNT(*) AS TotalItemsSold,

    -- Number of unique orders containing the product
    COUNT(DISTINCT oi.order_id) AS TotalOrders,

    -- Total revenue generated
    SUM(oi.price) AS TotalRevenue,

    -- Average selling price
    CAST(
        AVG(oi.price)
        AS DECIMAL(12,2)
    ) AS AverageSellingPrice,

    -- Total freight value
    SUM(oi.freight_value) AS TotalFreight

FROM dbo.olist_products_dataset AS p

INNER JOIN dbo.olist_order_items_dataset AS oi
    ON p.product_id = oi.product_id

LEFT JOIN dbo.product_category_name_translation AS t
    ON p.product_category_name = t.product_category_name

GROUP BY
    p.product_id,
    COALESCE(
        t.product_category_name_english,
        p.product_category_name,
        'Unknown'
    );
GO


-- =========================================================
-- Test the Product Performance View
-- =========================================================

SELECT TOP 10 *
FROM dbo.vw_ProductPerformance
ORDER BY TotalRevenue DESC;
GO

