-- Q1: Order Performance View
-- =========================================================

USE EcommerceAnalytics;
GO

CREATE OR ALTER VIEW dbo.vw_OrderPerformance
AS
SELECT
    o.order_id AS OrderID,
    o.customer_id AS CustomerID,
    o.order_status AS OrderStatus,

    TRY_CONVERT(
        DATETIME2,
        o.order_purchase_timestamp
    ) AS PurchaseDate,

    TRY_CONVERT(
        DATETIME2,
        o.order_delivered_customer_date
    ) AS DeliveredDate,

    TRY_CONVERT(
        DATETIME2,
        o.order_estimated_delivery_date
    ) AS EstimatedDeliveryDate,

    -- Total number of items in the order
    COUNT(oi.order_item_id) AS TotalItems,

    -- Total product revenue
    SUM(oi.price) AS TotalRevenue,

    -- Total freight cost
    SUM(oi.freight_value) AS TotalFreight,

    -- Delivery days
    CASE
        WHEN o.order_delivered_customer_date IS NOT NULL
        THEN DATEDIFF(
            DAY,
            TRY_CONVERT(
                DATETIME2,
                o.order_purchase_timestamp
            ),
            TRY_CONVERT(
                DATETIME2,
                o.order_delivered_customer_date
            )
        )
        ELSE NULL
    END AS DeliveryDays,

    -- Delivery classification
    CASE
        WHEN o.order_delivered_customer_date IS NULL
            THEN 'Not Delivered'

        WHEN TRY_CONVERT(
                DATETIME2,
                o.order_delivered_customer_date
             )
             <=
             TRY_CONVERT(
                DATETIME2,
                o.order_estimated_delivery_date
             )
            THEN 'Delivered On Time'

        ELSE 'Delivered Late'
    END AS DeliveryStatus

FROM dbo.olist_orders_dataset AS o

LEFT JOIN dbo.olist_order_items_dataset AS oi
    ON o.order_id = oi.order_id

GROUP BY
    o.order_id,
    o.customer_id,
    o.order_status,
    o.order_purchase_timestamp,
    o.order_delivered_customer_date,
    o.order_estimated_delivery_date;
GO

-- VERIFY THE RESULT
SELECT TOP 10 *
FROM dbo.vw_OrderPerformance;
GO

-- =========================================================
-- Q2: Customer 360 View
-- =========================================================

CREATE OR ALTER VIEW dbo.vw_Customer360
AS

SELECT
    c.customer_unique_id AS CustomerUniqueID,

    -- Customer location
    MAX(c.customer_city) AS CustomerCity,
    MAX(c.customer_state) AS CustomerState,

    -- Number of unique orders
    COUNT(DISTINCT o.order_id) AS TotalOrders,

    -- Number of products/items purchased
    COUNT(oi.order_item_id) AS TotalItems,

    -- Total revenue generated by the customer
    SUM(oi.price) AS TotalRevenue,

    -- Average order value
    CAST(
        SUM(oi.price) * 1.0
        / NULLIF(COUNT(DISTINCT o.order_id), 0)
        AS DECIMAL(12,2)
    ) AS AverageOrderValue

FROM dbo.olist_customers_dataset AS c

INNER JOIN dbo.olist_orders_dataset AS o
    ON c.customer_id = o.customer_id

INNER JOIN dbo.olist_order_items_dataset AS oi
    ON o.order_id = oi.order_id

GROUP BY
    c.customer_unique_id;
GO


-- =========================================================
-- Test the Customer 360 View
-- =========================================================

SELECT TOP 10 *
FROM dbo.vw_Customer360
ORDER BY TotalRevenue DESC;
GO

